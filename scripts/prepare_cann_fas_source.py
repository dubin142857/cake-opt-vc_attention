#!/usr/bin/env python3
"""Prepare the pinned CANN FAS sources and optional host-only provenance markers.

No CANN installation is needed for this step.  A first run fetches the two
official repositories; --offline requires both exact commits to be cached.
The official build downloads its other third-party dependencies separately.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import tarfile


ROOT = Path(__file__).resolve().parents[1]
MARKER_TOKEN = "vc_cann_fas_v901"
OP_ROOT = "attention/flash_attention_score"
API_FILE = f"{OP_ROOT}/op_api/aclnn_flash_attention_score.cpp"
TILING_FILE = f"{OP_ROOT}/op_host/flash_attention_score_tiling.cpp"
MARKER_FILE = f"{OP_ROOT}/vc_source_marker.h"
OPBASE_CMAKE = "cmake/third_party/opbase.cmake"


@dataclass(frozen=True)
class RepositoryLock:
    url: str
    commit: str
    tag: str | None = None


SOURCE_LOCK = RepositoryLock(
    "https://gitcode.com/cann/ops-transformer.git",
    "8038339a99bae113a7ae07f4547306d6d15bbddf",
    "v9.0.1",
)
# This is the dependency pin in the ops-transformer tag, not opbase's own tag.
OPBASE_LOCK = RepositoryLock(
    "https://gitcode.com/cann/opbase.git",
    "929902e577bb809a377a6ab17cb7b00a4dfddc1a",
)


MARKER_HEADER = r'''// Generated by prepare_cann_fas_source.py; host diagnostics only.
#ifndef VC_CANN_FAS_SOURCE_MARKER_H
#define VC_CANN_FAS_SOURCE_MARKER_H
#include <cerrno>
#include <cstdio>
#include <cstdlib>
#include <unistd.h>

static inline void VcCannFasSourceMarker(const char *phase, unsigned long long tilingKey)
{
    const char *path = std::getenv("VC_CANN_FAS_MARKER_FILE");
    if (path == nullptr || path[0] == '\0') {
        return;
    }
    std::FILE *file = std::fopen(path, "a");
    if (file == nullptr) {
        std::fprintf(stderr, "vc_cann_fas_v901: cannot open marker file %s (errno=%d)\n", path, errno);
        std::abort();
    }
    const int written = std::fprintf(file,
        "{\"token\":\"vc_cann_fas_v901\",\"phase\":\"%s\",\"pid\":%ld,\"tiling_key\":%llu}\n",
        phase, static_cast<long>(getpid()), tilingKey);
    const int flushed = std::fflush(file);
    const int closed = std::fclose(file);
    if (written < 0 || flushed != 0 || closed != 0) {
        std::fprintf(stderr, "vc_cann_fas_v901: cannot write marker file %s (errno=%d)\n", path, errno);
        std::abort();
    }
}
#endif
'''.encode("utf-8")


class PreparationError(RuntimeError):
    """The requested source state could not be established safely."""


def git(repo: Path, *args: str) -> bytes:
    result = subprocess.run(
        ["git", "-C", str(repo), *args], capture_output=True, check=False
    )
    if result.returncode:
        raise PreparationError(
            f"git {' '.join(args)} failed in {repo}: "
            f"{result.stderr.decode('utf-8', errors='replace').strip()}"
        )
    return result.stdout


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def ensure_checkout(path: Path, lock: RepositoryLock, offline: bool) -> None:
    if not path.exists():
        if offline:
            raise PreparationError(f"Offline cache missing: {path} ({lock.commit})")
        path.mkdir(parents=True)
        git(path, "init", "--quiet")
        git(path, "config", "core.autocrlf", "false")
        git(path, "remote", "add", "origin", lock.url)
    if not (path / ".git").exists():
        raise PreparationError(f"Refusing non-Git source directory: {path}")
    top = Path(git(path, "rev-parse", "--show-toplevel").decode().strip()).resolve()
    if top != path.resolve():
        raise PreparationError(f"Source must be its own checkout: {path}")
    head = subprocess.run(
        ["git", "-C", str(path), "rev-parse", "--verify", "HEAD"],
        capture_output=True, check=False,
    )
    if head.returncode:
        # A network interruption may leave the freshly initialized repository.
        # Retry only the empty, uncommitted checkout with the locked remote.
        if offline:
            raise PreparationError(f"Offline cache incomplete: {path} ({lock.commit})")
        if any(item.name != ".git" for item in path.iterdir()) or git(path, "ls-files"):
            raise PreparationError(f"Refusing nonempty checkout without HEAD: {path}")
        origin = git(path, "remote", "get-url", "origin").decode().strip()
        if origin != lock.url:
            raise PreparationError(f"Refusing incomplete checkout with unexpected origin: {origin}")
        git(path, "config", "core.autocrlf", "false")
        ref = f"refs/tags/{lock.tag}" if lock.tag else lock.commit
        git(path, "fetch", "--depth", "1", "origin", ref)
        fetched = git(path, "rev-parse", "FETCH_HEAD^{commit}").decode().strip()
        if fetched != lock.commit:
            raise PreparationError(f"Fetched {ref} is {fetched}, expected {lock.commit}")
        git(path, "checkout", "--quiet", "--detach", lock.commit)
        actual = git(path, "rev-parse", "HEAD").decode().strip()
    else:
        actual = head.stdout.decode().strip()
    if actual != lock.commit:
        raise PreparationError(f"Refusing HEAD {actual} in {path}; expected {lock.commit}")


def replace_once(data: bytes, old: bytes, new: bytes, label: str) -> bytes:
    if data.count(old) != 1:
        raise PreparationError(f"Pinned source anchor changed: {label}")
    return data.replace(old, new, 1)


def marker_patches(originals: dict[str, bytes]) -> dict[str, bytes]:
    api = originals[API_FILE]
    api = replace_once(
        api, b'#include "aclnn_flash_attention_score.h"',
        b'#include "../vc_source_marker.h"\n#include "aclnn_flash_attention_score.h"',
        "FAS API include",
    )
    signature = b"aclnnStatus aclnnFlashAttentionScoreGetWorkspaceSize("
    if api.count(signature) != 1:
        raise PreparationError("Pinned FAS workspace entry changed")
    body = api.index(b"\n{", api.index(signature)) + 2
    api = api[:body] + b'\n    VcCannFasSourceMarker("api", 0);' + api[body:]

    tiling = replace_once(
        originals[TILING_FILE], b"#include <queue>",
        b'#include "../vc_source_marker.h"\n#include <queue>', "FAS tiling include",
    )
    for function in (b"IsEmptyInputRegbase", b"IsEmptyInput"):
        old = b"if (" + function + b"(context)) {\n            return ge::GRAPH_SUCCESS;"
        new = (b"if (" + function + b"(context)) {\n"
               b'            VcCannFasSourceMarker("tiling", static_cast<unsigned long long>(context->GetTilingKey()));\n'
               b"            return ge::GRAPH_SUCCESS;")
        tiling = replace_once(tiling, old, new, function.decode())
    old = (b"    auto resultCode = TilingRegistryArch::GetInstance().DoTilingImpl(context);\n"
           b"    return resultCode;")
    new = (b"    auto resultCode = TilingRegistryArch::GetInstance().DoTilingImpl(context);\n"
           b"    if (resultCode == ge::GRAPH_SUCCESS) {\n"
           b'        VcCannFasSourceMarker("tiling", static_cast<unsigned long long>(context->GetTilingKey()));\n'
           b"    }\n    return resultCode;")
    tiling = replace_once(tiling, old, new, "FAS successful tiling return")
    return {API_FILE: api, TILING_FILE: tiling, MARKER_FILE: MARKER_HEADER}


def check_dirty(repo: Path, allowed: set[str]) -> None:
    for entry in git(repo, "ls-files", "-v", "-z").split(b"\0"):
        if entry and (entry[:1].islower() or entry[:1] == b"S"):
            raise PreparationError(f"Refusing hidden worktree changes (index flags) in {repo}: {entry!r}")
    # Index changes are never made by this script, including staged known patches.
    if git(repo, "diff", "--cached", "--name-only"):
        raise PreparationError(f"Refusing staged changes in {repo}")
    entries = git(repo, "status", "--porcelain=v1", "-z", "--untracked-files=all").split(b"\0")
    for entry in entries:
        if not entry:
            continue
        status = entry[:2]
        name = entry[3:].decode("utf-8")
        if name not in allowed or status not in (b" M", b"??"):
            raise PreparationError(f"Refusing unknown dirty change in {repo}: {entry!r}")


def audit_files(repo: Path, patches: dict[str, bytes]) -> tuple[dict, str]:
    """Hash every upstream file and compare its actual bytes before any writes."""
    records = {}
    kernel_records = []
    process = subprocess.Popen(
        ["git", "-C", str(repo), "archive", "--format=tar", "HEAD"],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    try:
        assert process.stdout is not None
        with tarfile.open(fileobj=process.stdout, mode="r|") as archive:
            for member in archive:
                if member.isdir():
                    continue
                if member.issym():
                    original = member.linkname.encode("utf-8")
                    current = os.readlink(repo / member.name).encode("utf-8")
                elif member.isfile():
                    stream = archive.extractfile(member)
                    assert stream is not None
                    original = stream.read()
                    current = (repo / member.name).read_bytes()
                else:
                    raise PreparationError(f"Unsupported upstream file type: {member.name}")
                prepared = patches.get(member.name, original)
                if current not in (original, prepared):
                    raise PreparationError(f"Unknown contents in {repo / member.name}")
                records[member.name] = {
                    "original_sha256": sha256(original),
                    "prepared_sha256": sha256(prepared),
                }
                if "/op_kernel/" in member.name:
                    if original != prepared:
                        raise PreparationError(f"Kernel patch forbidden: {member.name}")
                    kernel_records.append((member.name, sha256(original)))
        stderr = process.stderr.read() if process.stderr else b""
        if process.wait() != 0:
            raise PreparationError(f"git archive failed: {stderr.decode(errors='replace')}")
    finally:
        if process.poll() is None:
            process.kill()
            process.wait()
        if process.stdout:
            process.stdout.close()
        if process.stderr:
            process.stderr.close()
    if not kernel_records:
        raise PreparationError("No op_kernel sources found; cannot prove kernel unchanged")
    tracked = set(git(repo, "ls-tree", "-r", "--name-only", "-z", "HEAD").decode("utf-8").strip("\0").split("\0"))
    if tracked != set(records):
        raise PreparationError("Git archive omitted tracked sources; cannot produce a complete source audit")
    for name, prepared in patches.items():
        if name not in records:
            current_path = repo / name
            if current_path.exists() and current_path.read_bytes() != prepared:
                raise PreparationError(f"Unknown generated marker contents: {current_path}")
            records[name] = {"original_sha256": None, "prepared_sha256": sha256(prepared)}
    digest = hashlib.sha256()
    for name, checksum in sorted(kernel_records):
        digest.update(f"{name}\0{checksum}\n".encode("utf-8"))
    return records, digest.hexdigest()


def prepare_source(
    source_dir: Path,
    manifest_path: Path,
    third_party_dir: Path | None = None,
    offline: bool = False,
    *,
    source_lock: RepositoryLock = SOURCE_LOCK,
    opbase_lock: RepositoryLock = OPBASE_LOCK,
) -> dict:
    source_dir = source_dir.resolve()
    manifest_path = manifest_path.resolve()
    third_party_dir = (third_party_dir or source_dir / "third_party").resolve()
    shadow = source_dir.parent.parent / "ops-base"
    if shadow.exists():
        raise PreparationError(f"Official CMake would prefer unlocked dependency {shadow}; move it before preparing")
    ensure_checkout(source_dir, source_lock, offline)
    originals = {name: git(source_dir, "show", f"HEAD:{name}") for name in (API_FILE, TILING_FILE)}
    patches = marker_patches(originals)
    check_dirty(source_dir, set(patches))
    source_files, kernel_hash = audit_files(source_dir, patches)
    cmake = git(source_dir, "show", f"HEAD:{OPBASE_CMAKE}").decode("utf-8")
    match = re.search(r"set\(OPBASE_TAG_ID\s+([0-9a-f]{40})\)", cmake)
    if not match or match.group(1) != opbase_lock.commit:
        raise PreparationError("Official opbase.cmake pin differs from the locked opbase commit")
    opbase_dir = third_party_dir / "opbase"
    ensure_checkout(opbase_dir, opbase_lock, offline)
    check_dirty(opbase_dir, set())
    for name, prepared in patches.items():
        (source_dir / name).write_bytes(prepared)
    manifest = {
        "schema_version": 1,
        "upstream": {"url": source_lock.url, "tag": source_lock.tag, "commit": source_lock.commit},
        "source_dir": str(source_dir),
        "third_party_dir": str(third_party_dir),
        "marker_token": MARKER_TOKEN,
        "marker_environment": "VC_CANN_FAS_MARKER_FILE",
        "kernel_source_unchanged": True,
        "kernel_tree_sha256": kernel_hash,
        "kernel_tree_hash_format": "sha256 of sorted UTF-8 path + NUL + file sha256 + newline for every /op_kernel/ file",
        "modified_host_files": list(patches),
        "source_files": source_files,
        "dependencies": {
            "opbase": {
                "url": opbase_lock.url,
                "commit": opbase_lock.commit,
                "pin_source": OPBASE_CMAKE,
                "source_dir": str(opbase_dir),
                "git_tree": git(opbase_dir, "rev-parse", "HEAD^{tree}").decode().strip(),
            }
        },
        "other_build_dependencies": "Resolved by the official build; --offline here only covers the two source checkouts.",
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = manifest_path.with_name(manifest_path.name + ".tmp")
    temporary.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(manifest_path)
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, default=ROOT / "build/cann_fas_source")
    parser.add_argument("--manifest", type=Path, default=ROOT / "build/cann_fas_source_manifest.json")
    parser.add_argument("--third-party-dir", type=Path)
    parser.add_argument("--offline", action="store_true")
    args = parser.parse_args()
    try:
        manifest = prepare_source(args.source_dir, args.manifest, args.third_party_dir, args.offline)
    except (PreparationError, OSError, tarfile.TarError) as error:
        parser.exit(1, f"Source preparation failed: {error}\n")
    print(f"Prepared {manifest['upstream']['commit']} in {manifest['source_dir']}")
    print(f"Kernel source unchanged; tree SHA256 {manifest['kernel_tree_sha256']}")
    print(f"Manifest: {args.manifest.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
