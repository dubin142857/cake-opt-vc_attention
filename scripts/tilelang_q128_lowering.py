"""Candidate-local repair for TileLang 0.1.15 Q128 operand fences.

The normal CUDA pipeline determines each thread's physical fragment size.
Only this candidate then corrects the autogenerated fence to that size; the
registered backend and the shared TileLang installation remain untouched.
"""


def _fix_q128_fences(mod):
    """Repair known Q128 fences after the standard CUDA lowering pipeline."""
    from math import prod

    try:
        from tvm import DataType, tirx
        from tvm.tirx.stmt_functor import ir_transform, post_order_visit

        alloc_type = tirx.AllocBuffer
        if not hasattr(mod, "clone"):
            raise AttributeError("IRModule.clone")
    except (ImportError, AttributeError) as exc:
        raise RuntimeError(
            "Q128 requires TileLang 0.1.15 with the tirx AllocBuffer and "
            "per-compilation BackendContext APIs"
        ) from exc

    # Clone the complete module rather than reconstructing it from functions:
    # retain GlobalVars, attrs, global infos and any other module metadata.
    result = mod.clone()
    fence_counts = {"dots": 0, "pv": 0}
    expected_types = {"dots": "int32", "pv": "float32"}
    for gv, func in mod.functions.items():
        if not isinstance(func, tirx.PrimFunc):
            continue
        physical = {}

        def collect(node):
            if not isinstance(node, alloc_type):
                return
            buf = node.buffer
            name = buf.data.name
            if name not in expected_types:
                return
            if buf.scope() != "local":
                raise ValueError(f"Q128 fence buffer {name} must use local storage")
            try:
                extents = [int(extent) for extent in buf.shape]
            except (TypeError, ValueError) as exc:
                raise ValueError(f"Q128 fence buffer {name} needs a static physical shape") from exc
            dtype = DataType(buf.dtype)
            if any(extent < 1 for extent in extents) or dtype.bits != 32:
                raise ValueError(f"Unexpected Q128 physical allocation for {name}")
            if str(buf.dtype).split("x")[0] != expected_types[name]:
                raise ValueError(f"Unexpected Q128 allocation dtype for {name}: {buf.dtype}")
            physical[buf.data] = prod(extents) * dtype.bits * dtype.lanes // 32

        post_order_visit(func.body, collect)

        def rewrite(node):
            if not isinstance(node, tirx.Call) or getattr(node.op, "name", None) != "tl.warpgroup_fence_operand":
                return None
            if len(node.args) != 4:
                raise ValueError("Unexpected Q128 fence argument count")
            dtype, pointer, offset, old_count = node.args
            if not isinstance(pointer, tirx.Var) or pointer.name not in expected_types:
                raise ValueError("Q128 fence target must be the exact dots or pv allocation")
            if pointer not in physical:
                raise ValueError(f"Missing Q128 physical allocation for {pointer.name}")
            if getattr(dtype, "value", None) != expected_types[pointer.name]:
                raise ValueError(f"Unexpected Q128 fence dtype for {pointer.name}")
            if not isinstance(offset, tirx.IntImm) or int(offset) != 0:
                raise ValueError("Q128 fence offset must be a literal zero")
            count = physical[pointer]
            if not isinstance(old_count, tirx.IntImm) or int(old_count) not in (count, count * 2):
                raise ValueError(
                    f"Unexpected Q128 fence count for {pointer.name}: "
                    f"expected {count} or {count * 2}, got {old_count}"
                )
            fence_counts[pointer.name] += 1
            if int(old_count) == count:
                return None
            args = list(node.args)
            args[3] = tirx.IntImm(old_count.dtype, count)
            return tirx.Call(node.dtype, node.op, args, span=node.span)

        body = ir_transform(func.body, None, rewrite, ["tirx.Call"])
        result.update_func(gv, func.with_body(body))
    if not all(fence_counts.values()):
        raise ValueError("Q128 lowering must contain both dots and pv operand fences")
    return result


def create_q128_context(target):
    """Create a CUDA BackendContext used only for compiling the Q128 candidate."""
    try:
        from dataclasses import replace

        import tilelang
        from tilelang.backend.module import create_backend_context
        from tilelang.backend.pass_pipeline import PassPipeline
        from tilelang.env import env
    except (ImportError, AttributeError) as exc:
        raise RuntimeError(
            "Q128 requires TileLang 0.1.15 with the per-compilation BackendContext API"
        ) from exc
    if tilelang.__version__.split("+")[0] != "0.1.15":
        raise RuntimeError("Q128 lowering pins TileLang 0.1.15")
    try:
        base = create_backend_context(target, execution_backend=env.get_default_execution_backend())
        if base.target.kind.name != "cuda":
            raise ValueError("Q128 lowering requires a CUDA target")
        standard = base.module.get_pipeline(base.target)

        def lower(mod, resolved_target):
            return _fix_q128_fences(standard.lower(mod, resolved_target))

        pipelines = dict(base.module.pipelines)
        pipelines["cuda"] = PassPipeline("cuda", lower)
        local_module = replace(base.module, pipelines=pipelines)
        return replace(base, module=local_module)
    except (AttributeError, TypeError) as exc:
        raise RuntimeError(
            "Q128 requires TileLang 0.1.15 with the per-compilation BackendContext API"
        ) from exc
